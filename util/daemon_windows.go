package util

import (
	"os/exec"
	"syscall"
)

// detachedProcess and createNewProcessGroup keep the child alive after this
// console closes, and without a console window of its own.
const (
	detachedProcess       = 0x00000008
	createNewProcessGroup = 0x00000200
)

func detach(cmd *exec.Cmd) {
	cmd.SysProcAttr = &syscall.SysProcAttr{
		HideWindow:    true,
		CreationFlags: detachedProcess | createNewProcessGroup,
	}
}
